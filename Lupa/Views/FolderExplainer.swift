/// Folder and file explainer using the Apple Intelligence model (v9).
/// Only for items outside the verified `KnownLocations` list; runs on the Mac itself,
/// only when you click, and the answer is marked as generated.
struct FolderExplainer: View {
    let node: FileNode

    var body: some View {
        if #available(macOS 26.0, *) {
            #if canImport(FoundationModels)
            ExplainerBody(node: node)
            #endif
        }
    }
}

/// What the model returns, as short text.
struct FolderExplanationText: Equatable {
    enum Verdict: String { case safe, review, keep }
    let summary: String
    let verdict: Verdict
    let reason: String

    var verdictLabel: String {
        switch verdict {
        case .safe: return String(localized: "Probably safe to move")
        case .review: return String(localized: "Check before moving")
        case .keep: return String(localized: "Better to keep")
        }
    }
}

#if canImport(FoundationModels)
@available(macOS 26.0, *)
@Generable(description: "Short explanation of an item on a Mac's disk")
struct FolderExplanation {
    @Guide(description: "One sentence, in the user's language, saying what this item most likely is and which app or part of the system created it.")
    var summary: String

    @Guide(description: "safe: a cache, log, or temporary file the app recreates on its own; review: user or app data, depends on usage; keep: part of the system, of an installed app, or important data.")
    var verdict: Verdict

    @Guide(description: "One sentence, in the user's language, explaining the verdict and what happens if the item goes to the Trash.")
    var reason: String

    @Generable
    enum Verdict { case safe, review, keep }
}

@available(macOS 26.0, *)
@MainActor
private final class ExplainerCache {
    static let shared = ExplainerCache()
    var answers: [String: FolderExplanationText] = [:]
}

@available(macOS 26.0, *)
private struct ExplainerBody: View {
    let node: FileNode
    @State private var answer: FolderExplanationText?
    @State private var working = false
    @State private var failure: String?

    private var model: SystemLanguageModel { .default }

    var body: some View {
        Group {
            if let answer {
                HStack(alignment: .firstTextBaseline, spacing: 6) {
                    Image(systemName: "apple.intelligence").font(.caption).foregroundStyle(.secondary)
                    (Text(answer.verdictLabel + ". ").fontWeight(.semibold) + Text(answer.summary + " " + answer.reason))
                        .font(.caption).foregroundStyle(.secondary).lineLimit(2)
                }
                .help("Explanation generated by Apple Intelligence on this Mac. It can be wrong: check before moving.\n\n\(answer.summary)\n\n\(answer.verdictLabel): \(answer.reason)")
            } else if working {
                HStack(spacing: 6) {
                    ProgressView().controlSize(.mini)
                    Text("Figuring out what this item is…").font(.caption).foregroundStyle(.secondary)
                }
            } else if let failure {
                Text(failure).font(.caption).foregroundStyle(.secondary).lineLimit(2)
            } else {
                switch model.availability {
                case .available:
                    Button { explain() } label: {
                        Label("What's This?", systemImage: "apple.intelligence").font(.caption.weight(.medium))
                    }
                    .buttonStyle(.plain)
                    .foregroundStyle(.primary.opacity(0.8))   // no blue: the only vivid color is the disk's
                    .help("Asks Apple Intelligence, on this Mac, to explain this item. Nothing leaves your computer.")
                case .unavailable(.appleIntelligenceNotEnabled):
                    Text("Turn on Apple Intelligence in System Settings so Legroom can explain unfamiliar items.")
                        .font(.caption).foregroundStyle(.tertiary).lineLimit(2)
                case .unavailable(.modelNotReady):
                    Text("The Apple Intelligence model is still downloading; explanations will be available once it finishes.")
                        .font(.caption).foregroundStyle(.tertiary).lineLimit(2)
                default:
                    EmptyView()
                }
            }
        }
        .task(id: node.path) {
            answer = ExplainerCache.shared.answers[node.path]
            working = false
            failure = nil
        }
    }

    private func explain() {
        let path = node.path
        let prompt = Self.prompt(for: node)
        working = true
        failure = nil
        Task {
            do {
                let session = LanguageModelSession(instructions: """
                    You help people understand what takes up space on their Mac. You receive the path and some \
                    details of an item and explain, in the user's language (\(Bundle.main.preferredLocalizations.first ?? "en")), \
                    what it most likely is. Be conservative: when in doubt, use review or keep. Never make up \
                    app names that don't appear in the data; if you don't know, say that you can't be sure.
                    """)
                let r = try await session.respond(to: prompt, generating: FolderExplanation.self)
                let v: FolderExplanationText.Verdict = switch r.content.verdict {
                case .safe: .safe
                case .review: .review
                case .keep: .keep
                }
                let text = FolderExplanationText(summary: r.content.summary, verdict: v, reason: r.content.reason)
                ExplainerCache.shared.answers[path] = text
                if node.path == path { answer = text }
            } catch {
                if node.path == path { failure = String(localized: "Couldn't explain this item right now.") }
            }
            if node.path == path { working = false }
        }
    }

    /// Metadata only: name, path with ~, size, dates, and the largest items inside.
    static func prompt(for n: FileNode) -> String {
        let home = NSHomeDirectory()
        let path = n.path.hasPrefix(home) ? "~" + n.path.dropFirst(home.count) : n.path
        var lines = [
            "Path: \(path)",
            "Kind: \(n.isDirectory ? (n.isPackage ? "package" : "folder") : "file") (\(n.category.label))",
            "Size on disk: \(Format.bytes(n.allocatedSize))",
        ]
        if n.isDirectory { lines.append("Items inside: \(n.fileCount)") }
        if let m = n.modified { lines.append("Modified: \(m.formatted(date: .abbreviated, time: .omitted))") }
        if let a = n.accessed { lines.append("Last accessed: \(a.formatted(date: .abbreviated, time: .omitted))") }
        let inside = n.children.prefix(6).map { "\($0.name) (\(Format.bytes($0.allocatedSize)))" }
        if !inside.isEmpty { lines.append("Largest items inside: " + inside.joined(separator: ", ")) }
        return lines.joined(separator: "\n")
    }
}
#endif
